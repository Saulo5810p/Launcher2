#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
01_gradle_scaffold.py  -  Launcher2 (Android 4.0) -> projeto Gradle compilavel no Termux

Rode na RAIZ do repositorio:   python3 01_gradle_scaffold.py [opcoes]

O que faz (idempotente):
  * cria settings.gradle, build.gradle, gradle.properties, .gitignore (so o que falta/mudou)
  * modulo unico na raiz, SEM mover arquivos: sourceSets apontam para src/, res/ e
    AndroidManifest.xml (os scripts seguintes continuam trabalhando em res/ e src/)
  * namespace  = com.android.launcher   (mantem "import com.android.launcher.R" do codigo)
    applicationId = com.xaulinxs.launcher2, compileSdk/targetSdk 34
  * gradle.properties com android.nonFinalResIds=false (o codigo usa R.id em switch/case)
  * wrapper: copia de outro projeto (--wrapper-from) ou gera com `gradle wrapper`
  * move os arquivos so do build AOSP (Android.mk, CleanSpec.mk, scripts py2...) para legacy/

Opcoes:
  --dry-run              so mostra o que faria
  --wrapper-from PASTA   copia gradlew, gradlew.bat e gradle/wrapper/ de outro projeto seu
  --gradle-version X     versao do wrapper (padrao 9.6.1)
  --agp-version X        versao do Android Gradle Plugin (padrao 8.7.0)
  --sdk-dir PASTA        grava local.properties (senao usa ANDROID_HOME/ANDROID_SDK_ROOT)
  --aapt2 CAMINHO        grava android.aapt2FromMavenOverride no gradle.properties (Termux)
  --keep-legacy          nao move Android.mk & cia para legacy/
"""
import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

MARK = "generated by 01_gradle_scaffold.py"

LEGACY_FILES = ["Android.mk", "CleanSpec.mk", "MODULE_LICENSE_APACHE2",
                "fill_screens.py", "print_db.py"]


def log(msg):
    print(msg)


def write_file(path: Path, content: str, dry: bool, marker=True):
    """Escreve so se mudou. Se existir um arquivo sem a nossa marca, guarda .orig uma vez."""
    if path.exists():
        old = path.read_text(encoding="utf-8", errors="replace")
        if old == content:
            log(f"  ok        {path}")
            return
        if MARK not in old and not path.with_name(path.name + ".orig").exists():
            if not dry:
                shutil.copy2(path, path.with_name(path.name + ".orig"))
            log(f"  backup    {path}.orig")
        log(f"  atualiza  {path}")
    else:
        log(f"  cria      {path}")
    if not dry:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def build_gradle(agp):
    return f"""// {MARK}
plugins {{
    id 'com.android.application' version '{agp}'
}}

android {{
    // namespace define o pacote da classe R (o codigo importa com.android.launcher.R).
    // O ID instalavel do app e' o applicationId, que e' outro.
    namespace 'com.android.launcher'
    compileSdk 34

    defaultConfig {{
        applicationId 'com.xaulinxs.launcher2'
        minSdk 24
        targetSdk 34
        versionCode 1
        versionName '4.0.1'
    }}

    sourceSets {{
        main {{
            manifest.srcFile 'AndroidManifest.xml'
            java.srcDirs = ['src']
            res.srcDirs = ['res']
        }}
    }}

    compileOptions {{
        sourceCompatibility JavaVersion.VERSION_1_8
        targetCompatibility JavaVersion.VERSION_1_8
    }}

    buildTypes {{
        release {{
            minifyEnabled false
        }}
    }}

    lint {{
        abortOnError false
        checkReleaseBuilds false
    }}
}}
"""


def settings_gradle():
    return f"""// {MARK}
pluginManagement {{
    repositories {{
        google()
        mavenCentral()
        gradlePluginPortal()
    }}
}}
dependencyResolutionManagement {{
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {{
        google()
        mavenCentral()
    }}
}}
rootProject.name = 'Launcher2'
"""


def gradle_properties(aapt2):
    lines = [
        f"# {MARK}",
        "org.gradle.jvmargs=-Xmx2g -Dfile.encoding=UTF-8",
        "org.gradle.daemon=true",
        "android.useAndroidX=false",
        "android.enableJetifier=false",
        "# O codigo AOSP usa R.id.* dentro de switch/case: precisa de constantes finais.",
        "android.nonFinalResIds=false",
        "android.nonTransitiveRClass=false",
    ]
    if aapt2:
        lines.append(f"android.aapt2FromMavenOverride={aapt2}")
    else:
        lines.append("# Termux: descomente e aponte para o aapt2 do seu SDK, se precisar")
        lines.append("# android.aapt2FromMavenOverride=/data/data/com.termux/files/home/android-sdk/build-tools/34.0.0/aapt2")
    return "\n".join(lines) + "\n"


GITIGNORE_LINES = [".gradle/", "build/", "local.properties", "*.apk", "*.aab",
                   ".backup_tablet/", "*.orig", "*.bak"]


def ensure_gitignore(dry):
    p = Path(".gitignore")
    old = p.read_text(encoding="utf-8") if p.exists() else ""
    have = set(l.strip() for l in old.splitlines())
    add = [l for l in GITIGNORE_LINES if l not in have]
    if not add:
        log("  ok        .gitignore")
        return
    log(f"  atualiza  .gitignore (+{len(add)} linhas)")
    if not dry:
        sep = "" if (not old or old.endswith("\n")) else "\n"
        p.write_text(old + sep + "\n".join(add) + "\n", encoding="utf-8")


def ensure_local_properties(sdk_dir, dry):
    p = Path("local.properties")
    if p.exists():
        log("  ok        local.properties (ja existe)")
        return
    sdk = sdk_dir or os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT")
    if not sdk:
        log("  aviso     local.properties nao criado (use --sdk-dir ou ANDROID_HOME)")
        return
    log(f"  cria      local.properties (sdk.dir={sdk})")
    if not dry:
        p.write_text(f"sdk.dir={sdk}\n", encoding="utf-8")


def ensure_wrapper(wrapper_from, gradle_version, dry):
    jar = Path("gradle/wrapper/gradle-wrapper.jar")
    if Path("gradlew").exists() and jar.exists():
        log("  ok        gradlew + gradle/wrapper")
        return
    if wrapper_from:
        src = Path(wrapper_from).expanduser()
        need = [src / "gradlew", src / "gradle" / "wrapper" / "gradle-wrapper.jar",
                src / "gradle" / "wrapper" / "gradle-wrapper.properties"]
        if not all(x.exists() for x in need):
            log(f"  ERRO      {src} nao tem gradlew + gradle/wrapper completos")
            return
        log(f"  copia     wrapper de {src}")
        if not dry:
            (Path("gradle") / "wrapper").mkdir(parents=True, exist_ok=True)
            shutil.copy2(src / "gradlew", "gradlew")
            os.chmod("gradlew", 0o755)
            if (src / "gradlew.bat").exists():
                shutil.copy2(src / "gradlew.bat", "gradlew.bat")
            shutil.copy2(src / "gradle" / "wrapper" / "gradle-wrapper.jar", jar)
            shutil.copy2(src / "gradle" / "wrapper" / "gradle-wrapper.properties",
                         "gradle/wrapper/gradle-wrapper.properties")
        return
    if shutil.which("gradle"):
        log(f"  gera      wrapper via `gradle wrapper --gradle-version {gradle_version}`")
        if not dry:
            r = subprocess.run(["gradle", "wrapper", "--gradle-version", gradle_version])
            if r.returncode != 0:
                log("  aviso     `gradle wrapper` falhou; use --wrapper-from de outro projeto seu")
        return
    log("  aviso     sem wrapper: rode de novo com --wrapper-from ~/OutroProjeto "
        "(ou instale o gradle e rode `gradle wrapper`)")


def move_legacy(dry, keep):
    if keep:
        return
    dest = Path("legacy")
    moved = False
    for name in LEGACY_FILES:
        p = Path(name)
        if not p.exists():
            continue
        moved = True
        log(f"  move      {name} -> legacy/{name}")
        if dry:
            continue
        dest.mkdir(exist_ok=True)
        in_git = Path(".git").exists() and shutil.which("git")
        done = False
        if in_git:
            r = subprocess.run(["git", "mv", str(p), str(dest / name)],
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            done = (r.returncode == 0)
        if not done:
            shutil.move(str(p), str(dest / name))
    if not moved:
        log("  ok        legacy (nada a mover)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--wrapper-from")
    ap.add_argument("--gradle-version", default="9.6.1")
    ap.add_argument("--agp-version", default="8.7.0")
    ap.add_argument("--sdk-dir")
    ap.add_argument("--aapt2")
    ap.add_argument("--keep-legacy", action="store_true")
    a = ap.parse_args()

    if not (Path("AndroidManifest.xml").exists() and Path("src").is_dir() and Path("res").is_dir()):
        sys.exit("ERRO: rode na raiz do repo Launcher2 (onde ficam AndroidManifest.xml, src/ e res/).")

    log("== 01: estrutura Gradle ==")
    write_file(Path("settings.gradle"), settings_gradle(), a.dry_run)
    write_file(Path("build.gradle"), build_gradle(a.agp_version), a.dry_run)
    write_file(Path("gradle.properties"), gradle_properties(a.aapt2), a.dry_run)
    ensure_gitignore(a.dry_run)
    ensure_local_properties(a.sdk_dir, a.dry_run)
    ensure_wrapper(a.wrapper_from, a.gradle_version, a.dry_run)
    move_legacy(a.dry_run, a.keep_legacy)
    log("== 01 concluido ==" + (" (dry-run)" if a.dry_run else ""))


if __name__ == "__main__":
    main()
